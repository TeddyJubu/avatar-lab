import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { format, resolveConfig } from 'prettier'
import { build } from 'rolldown'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const check = process.argv.includes('--check')
const stale = []

const sync = async (relativePath, expected) => {
  const target = path.join(root, relativePath)
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current === expected) return
  if (check) stale.push(relativePath)
  else await writeFile(target, expected)
}

const updateJson = async (relativePath, update) => {
  const current = JSON.parse(await readFile(path.join(root, relativePath), 'utf8'))
  update(current)
  const filepath = path.join(root, relativePath)
  const options = { ...(await resolveConfig(filepath)), filepath }
  await sync(relativePath, await format(JSON.stringify(current), options))
}

// The MCP package name and version are the single source of truth for the server and the plugin.
const { name, version } = JSON.parse(
  await readFile(path.join(root, 'packages/avatar-mcp/package.json'), 'utf8')
)
const serverSource = await readFile(path.join(root, 'packages/avatar-mcp/src/server.ts'), 'utf8')
await sync(
  'packages/avatar-mcp/src/server.ts',
  serverSource.replace(
    /export const AVATAR_MCP_VERSION = '[^']*'/,
    `export const AVATAR_MCP_VERSION = '${version}'`
  )
)
await updateJson('plugins/avatar-lab/.claude-plugin/plugin.json', plugin => {
  plugin.version = version
})
await updateJson('.claude-plugin/marketplace.json', marketplace => {
  marketplace.plugins.find(plugin => plugin.name === 'avatar-lab').version = version
})

// Plugins are installed from git without dependencies, so the server ships as one file.
const result = await build({
  input: path.join(root, 'packages/avatar-mcp/src/cli.ts'),
  platform: 'node',
  logLevel: 'silent',
  write: false,
  external: ['@resvg/resvg-js'],
  resolve: {
    alias: {
      '@bible-strong/avatar-core/schema': path.join(
        root,
        'packages/avatar-core/src/avatarDefinition.schema.json'
      ),
      '@bible-strong/avatar-core': path.join(root, 'packages/avatar-core/src/index.ts'),
    },
  },
  output: { format: 'esm', minify: true, codeSplitting: false },
})
const chunk = result.output.find(item => item.type === 'chunk')
if (!chunk) throw new Error('Avatar MCP server bundle was not generated.')
const code = chunk.code.replace(/^#!.*\n/, '')
await sync(
  'plugins/avatar-lab/server/avatar-mcp.mjs',
  `#!/usr/bin/env node\n// Generated by scripts/generate-claude-plugin.mjs from packages/avatar-mcp. Do not edit.\n// ${name} ${version} - AGPL-3.0-only - https://github.com/TeddyJubu/avatar-lab\n${code}`
)

if (stale.length) {
  throw new Error(`Claude plugin files are stale: ${stale.join(', ')}. Run pnpm plugin.`)
}
